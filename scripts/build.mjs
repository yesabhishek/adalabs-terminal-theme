// ── contrast audit ────────────────────────────────────────────
function audit(p) {
  const issues = [];
  const need = (label, fg, bg, min) => { const c = contrast(fg, bg); if (c < min) issues.push(`${label} ${c.toFixed(2)} < ${min}`); };
  for (const [role, c] of Object.entries(p.syntax)) need(`syntax.${role}`, c, p.bg, role === "comment" ? 3.5 : role === "op" ? 4 : 4.5);
  for (const [role, c] of Object.entries(p.ansi)) need(`ansi.${role}`, c, p.bg, 4);
  need("fg", p.fg, p.bg, 9); need("fg/sidebar", p.fg, p.bg2, 9);
  need("muted", p.muted, p.bg2, 4.5); need("faint (line numbers)", p.faint, p.bg, 2.2);
  need("button text", p.accentFg, p.accent, 4.5);
  return issues;
}

// ── write ─────────────────────────────────────────────────────
const label = (p) => `AdaLabs ${p.name}`;
let failed = 0;
for (const p of palettes) {
  const issues = audit(p);
  if (issues.length) { failed++; console.log(`✗ ${p.name}: ${issues.join("; ")}`); }
}
if (failed) { console.error(`\n${failed} palette(s) failed contrast checks.`); process.exit(1); }
console.log(`✓ ${palettes.length} palettes pass contrast checks`);
if (checkOnly) process.exit(0);

const themesDir = join(root, "themes");
mkdirSync(themesDir, { recursive: true });
for (const f of readdirSync(themesDir)) if (f.endsWith(".json")) unlinkSync(join(themesDir, f));
for (const p of palettes) {
  const theme = { $schema: "vscode://schemas/color-theme", name: label(p), type: p.type, semanticHighlighting: true, colors: workbench(p), tokenColors: tokenColors(p), semanticTokenColors: semanticTokenColors(p) };
  writeFileSync(join(themesDir, `${p.slug}.json`), JSON.stringify(theme, null, 2) + "\n");
}

const pkgPath = join(root, "package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
pkg.contributes.themes = palettes.map((p) => ({ label: label(p), uiTheme: p.type === "dark" ? "vs-dark" : "vs", path: `./themes/${p.slug}.json` }));
writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + "\n");
console.log(`✓ wrote ${palettes.length} themes and updated package.json`);
